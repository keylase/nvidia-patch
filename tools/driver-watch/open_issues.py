#!/usr/bin/env python3
"""Open one GitHub issue per candidate printed by driver_watch.py.

Reads the candidate list (JSON) from the file given as argument, skips every
driver that already has an issue (open or closed) with exactly the title this
script uses or the repository's request template title ("New driver support
(version X)"), and creates the rest with the `gh` CLI. A user report that merely
mentions a version does not count. Needs GH_TOKEN and
GH_REPO (or a git remote) in the environment. With --dry-run nothing is
created.

--issues-out writes {"<platform>:<version>": {"number": N, "state": "OPEN"}} for
every driver that has an issue, so that generate_patches.py can link to it and
leave drivers whose issue was closed alone.

A failing `gh` call for one driver is reported and does not stop the others; the
exit code is then 1. If the lookup of a driver's issue fails, it is recorded as
UNKNOWN and generate_patches.py leaves that driver alone (never assume "no issue").
"""

import argparse
import json
import re
import subprocess
import sys

VERSION_RE = re.compile(r"^[0-9]+(\.[0-9]+)*$")
PLATFORM_TAG = {"linux": "linux:", "windows": "win:"}


def gh(*args):
    result = subprocess.run(["gh", *args], check=True, capture_output=True, text=True)
    return result.stdout


def find_issue(platform, version):
    """('bot' | 'request', number, state) of the issue that already covers this driver, or None.

    Only two kinds of title count: the bot's own, and the repository's request template
    ("New driver support (version X)"). A user report that merely mentions the version counts
    for nothing, and the version must match whole ("535.86" is not "535.86.05"). The bot's
    own title is preferred. A request carries no platform, so it only means "already
    covered": it never selects a "Fixes #N" link or a closed-issue skip.
    """
    out = gh("issue", "list", "--state", "all", "--search", f'"{version}" in:title', "--json", "number,title,state")
    ours = re.compile(rf"^{re.escape(title_for(platform, version))}$")
    request = re.compile(rf"^New driver support \(version {re.escape(version)}\)\.?$", re.IGNORECASE)
    issues = json.loads(out)
    for kind, pattern in (("bot", ours), ("request", request)):
        for issue in issues:
            if pattern.match(issue["title"].strip()):
                return kind, issue["number"], issue["state"]
    return None


def title_for(platform, version):
    return f"{PLATFORM_TAG[platform]} new driver {version} needs a patch"


def render(candidate):
    version, name, date, url = (candidate[k] for k in ("version", "name", "date", "url"))
    if candidate["platform"] == "linux":
        title = title_for("linux", version)
        manual = f"the **Generate Linux patches** workflow with version `{version}` and mode `search`"
        test = "`tools/patch-tester/patch-tester.sh`"
    else:
        variant = "Studio Driver" if "Studio" in name else "DCH"
        title = title_for("windows", version)
        manual = f"the **Generate Windows patches** workflow with version `{version}` and variant `{variant}`"
        test = "`win/tools/patch-tester`"
    body = (
        f"NVIDIA released **{name} {version}** on {date}. There is no patch for it in this repository yet.\n\n"
        f"Download: {url}\n\n"
        "The `Detect new drivers` workflow also tries to generate the patch and collects the result in a draft "
        "pull request (branch `bot/new-drivers`). If it cannot, the reason is in the summary of the workflow run, "
        "and the patch can be generated by hand with "
        f"{manual}.\n\n"
        f"Whatever way it is generated, test it with {test} (13 concurrent sessions) before merging. "
        "Closing this issue stops the workflow from generating the patch again.\n"
    )
    return title, body


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("candidates", help="JSON file written by driver_watch.py")
    parser.add_argument("--dry-run", action="store_true", help="print what would be opened")
    parser.add_argument("--issues-out", help="write the issue number and state of every driver here")
    args = parser.parse_args()

    with open(args.candidates, encoding="utf-8") as handle:
        candidates = json.load(handle)
    print(f"{len(candidates)} candidate(s)")

    issues, failures = {}, 0
    for candidate in candidates:
        platform, version = candidate["platform"], candidate["version"]
        if platform not in PLATFORM_TAG or not VERSION_RE.match(version):
            print("skipping an unexpected platform or version string")
            continue
        key = f"{platform}:{version}"
        try:
            existing = find_issue(platform, version)
        except Exception as exc:  # gh failure or unexpected output: whether an issue exists is unknown
            failures += 1
            issues[key] = {"state": "UNKNOWN"}  # generate_patches.py leaves such a driver alone
            print(f"::warning::{key}: could not look up its issue ({type(exc).__name__}: {str(exc)[:200]})")
            continue
        if existing is not None:
            kind, number, state = existing
            if kind == "bot":
                issues[key] = {"number": number, "state": state}
                print(f"{key}: issue #{number} ({state}) already exists, skipping")
            else:
                print(f"{key}: covered by the request #{number} ({state}), not opening another issue")
            continue
        title, body = render(candidate)
        if args.dry_run:
            print(f"DRY RUN, would open: {title}")
            continue
        try:
            url = gh("issue", "create", "--title", title, "--body", body, "--label", "enhancement").strip()
        except subprocess.CalledProcessError as exc:
            failures += 1
            print(f"::warning::{key}: could not open the issue: {(exc.stderr or '').strip()[:200]}")
            continue
        print(f"opened: {title} ({url})")
        match = re.search(r"/issues/(\d+)$", url)
        if match:
            issues[key] = {"number": int(match.group(1)), "state": "OPEN"}

    if args.issues_out:
        with open(args.issues_out, "w", encoding="utf-8") as handle:
            json.dump(issues, handle)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
