#!/usr/bin/env python3
"""Open one GitHub issue per candidate printed by driver_watch.py.

Reads the candidate list (JSON) from the file given as argument, skips every
driver version that already appears in the title of any issue (open or closed,
by anyone) and creates the rest with the `gh` CLI. Needs GH_TOKEN and GH_REPO
(or a git remote) in the environment. With --dry-run nothing is created.
"""

import argparse
import json
import re
import subprocess
import sys

VERSION_RE = re.compile(r"^[0-9]+(\.[0-9]+)*$")


def gh(*args):
    result = subprocess.run(["gh", *args], check=True, capture_output=True, text=True)
    return result.stdout


def find_issue(version):
    """Number of the issue that already names this version in its title, or None."""
    out = gh("issue", "list", "--state", "all", "--search", f'"{version}" in:title', "--json", "number,title")
    # Whole version only: "535.86" must not match "535.86.05" or "1535.86".
    whole = re.compile(r"(?<!\d)(?<!\d\.)" + re.escape(version) + r"(?!\.?\d)")
    for issue in json.loads(out):
        if whole.search(issue["title"]):
            return issue["number"]
    return None


def render(candidate):
    version, name, date, url = (candidate[k] for k in ("version", "name", "date", "url"))
    if candidate["platform"] == "linux":
        title = f"linux: new driver {version} needs a patch"
        manual = f"the **Generate Linux patches** workflow with version `{version}` and mode `search`"
        test = "`tools/patch-tester/patch-tester.sh`"
    else:
        variant = "Studio Driver" if "Studio" in name else "DCH"
        title = f"win: new driver {version} needs a patch"
        manual = f"the **Generate Windows patches** workflow with version `{version}` and variant `{variant}`"
        test = "`win/tools/patch-tester`"
    body = (
        f"NVIDIA released **{name} {version}** on {date}. There is no patch for it in this repository yet.\n\n"
        f"Download: {url}\n\n"
        "The `Detect new drivers` workflow also tries to generate the patch and collects the result in a draft "
        "pull request (branch `bot/new-drivers`). If it cannot, the pull request description says why, and the "
        f"patch can be generated by hand with {manual}.\n\n"
        f"Whatever way it is generated, test it with {test} (13 concurrent sessions) before merging.\n"
    )
    return title, body


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("candidates", help="JSON file written by driver_watch.py")
    parser.add_argument("--dry-run", action="store_true", help="print what would be opened")
    parser.add_argument("--issues-out", help="write {version: issue number} for existing and new issues here")
    args = parser.parse_args()

    with open(args.candidates, encoding="utf-8") as handle:
        candidates = json.load(handle)
    print(f"{len(candidates)} candidate(s)")

    numbers = {}
    for candidate in candidates:
        version = candidate["version"]
        if not VERSION_RE.match(version):
            print("skipping an unexpected version string")
            continue
        existing = find_issue(version)
        if existing is not None:
            print(f"{candidate['platform']} {version}: issue #{existing} already exists, skipping")
            numbers[version] = existing
            continue
        title, body = render(candidate)
        if args.dry_run:
            print(f"DRY RUN, would open: {title}")
            continue
        url = gh("issue", "create", "--title", title, "--body", body, "--label", "enhancement").strip()
        print(f"opened: {title} ({url})")
        match = re.search(r"/issues/(\d+)$", url)
        if match:
            numbers[version] = int(match.group(1))

    if args.issues_out:
        with open(args.issues_out, "w", encoding="utf-8") as handle:
            json.dump(numbers, handle)
    return 0


if __name__ == "__main__":
    sys.exit(main())
